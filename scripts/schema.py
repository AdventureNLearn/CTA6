def era_path(era: str) -> Path:
    return TIMELINE_DIR / f"{ERA_SLUGS[era]}.md"


def region_path(region: str) -> Path:
    return REGIONS_DIR / f"{REGION_SLUGS[region]}.md"


def theme_path(theme: str) -> Path:
    return THEMES_DIR / f"{THEME_SLUGS[theme]}.md"


def era_href(era: str, from_sources: bool = False) -> str:
    rel = "../../timeline" if from_sources else "."
    return f"{rel}/{ERA_SLUGS[era]}.md"


def region_href(region: str, from_timeline: bool = False) -> str:
    rel = "../sources/regions" if from_timeline else "../regions"
    return f"{rel}/{REGION_SLUGS[region]}.md"


def theme_href(theme: str, from_timeline: bool = False) -> str:
    rel = "../sources/themes" if from_timeline else "."
    return f"{rel}/{THEME_SLUGS[theme]}.md"
